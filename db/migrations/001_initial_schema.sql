-- IMPORTANTES:
-- - dim_producto NO tiene area_habitual
-- - dim_usuario.rut_usuario es PK (sin id_usuario)
-- - dim_usuario.area_asignada es TEXTO (nombre de área o 'Todas'), no FK
-- - dim_proveedor.rut_proveedor es PK (sin id_proveedor)
-- - hecho_inventario NO tiene costo_total; cantidad es decimal
-- - hecho_venta_fudo es tabla independiente
-- - dim_fecha usa solo "anio" (la columna duplicada "año" se eliminó en 007)

-- dim_fecha
CREATE TABLE IF NOT EXISTS dim_fecha (
    id_fecha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE UNIQUE NOT NULL,
    dia SMALLINT,
    mes SMALLINT,
    anio SMALLINT
);

-- dim_area
CREATE TABLE IF NOT EXISTS dim_area (
    id_area INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_area VARCHAR(50) NOT NULL,
    descripcion_area VARCHAR(200) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- dim_usuario (PK: rut_usuario)
CREATE TABLE IF NOT EXISTS dim_usuario (
    rut_usuario VARCHAR(12) PRIMARY KEY,
    nombre_usuario VARCHAR(100) NOT NULL,
    rol VARCHAR(30) NOT NULL CHECK (rol IN ('Administrador', 'Operario')),
    -- Nombre del área asignada o 'Todas' para administradores (no es FK).
    area_asignada VARCHAR(30) NOT NULL,
    password_hash TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- dim_proveedor (PK: rut_proveedor)
CREATE TABLE IF NOT EXISTS dim_proveedor (
    rut_proveedor VARCHAR(12) PRIMARY KEY,
    nombre_proveedor VARCHAR(150) NOT NULL,
    contacto_proveedor VARCHAR(150) NOT NULL,
    tipo_proveedor VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- dim_producto (SIN area_habitual)
CREATE TABLE IF NOT EXISTS dim_producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(150) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    unidad_medida VARCHAR(30) NOT NULL,
    costo_base NUMERIC NOT NULL DEFAULT 0,
    stock_minimo NUMERIC NOT NULL DEFAULT 0,
    stock_maximo NUMERIC NOT NULL DEFAULT 100,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- dim_tipo_movimiento
CREATE TABLE IF NOT EXISTS dim_tipo_movimiento (
    id_tipo_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento VARCHAR(50) NOT NULL,
    factor_stock INTEGER NOT NULL CHECK (factor_stock IN (1, -1)),
    descripcion VARCHAR(200) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- dim_evento
CREATE TABLE IF NOT EXISTS dim_evento (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_evento VARCHAR(150) NOT NULL,
    nombre_artista VARCHAR(150) NOT NULL,
    tipo_evento VARCHAR(50) NOT NULL,
    costo_artista NUMERIC NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    -- Fecha de presentación del artista (migración 006).
    fecha_evento DATE
);

CREATE INDEX IF NOT EXISTS idx_dim_evento_fecha_evento
    ON dim_evento (fecha_evento);

-- hecho_inventario (SIN costo_total)
CREATE TABLE IF NOT EXISTS hecho_inventario (
    id_hecho_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fecha INTEGER NOT NULL REFERENCES dim_fecha(id_fecha),
    id_producto INTEGER NOT NULL REFERENCES dim_producto(id_producto),
    id_area INTEGER NOT NULL REFERENCES dim_area(id_area),
    id_tipo_movimiento INTEGER NOT NULL REFERENCES dim_tipo_movimiento(id_tipo_movimiento),
    rut_usuario VARCHAR(12) NOT NULL REFERENCES dim_usuario(rut_usuario),
    rut_proveedor VARCHAR(12) REFERENCES dim_proveedor(rut_proveedor),
    id_evento INTEGER REFERENCES dim_evento(id_evento),
    cantidad NUMERIC NOT NULL CHECK (cantidad > 0),
    costo_unitario NUMERIC NOT NULL,
    observacion TEXT,
    fecha_hora_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- hecho_venta_fudo (independiente de hecho_inventario)
CREATE TABLE IF NOT EXISTS hecho_venta_fudo (
    id_venta_fudo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento INTEGER REFERENCES dim_evento(id_evento),
    fecha_venta DATE,
    origen_archivo VARCHAR(255),
    datos_raw JSONB,
    total_venta NUMERIC,
    cantidad_total NUMERIC,
    producto_identificado VARCHAR(150),
    id_producto_relacionado INTEGER REFERENCES dim_producto(id_producto),
    importado_por VARCHAR(12) REFERENCES dim_usuario(rut_usuario),
    fecha_importacion TIMESTAMPTZ DEFAULT NOW(),
    hash_registro VARCHAR(64)
);

COMMENT ON COLUMN hecho_venta_fudo.datos_raw IS
    'Datos originales del registro importado desde FUDO en formato JSON';
COMMENT ON COLUMN hecho_venta_fudo.hash_registro IS
    'Hash SHA256 utilizado para detectar importaciones duplicadas';
COMMENT ON COLUMN dim_evento.fecha_evento IS
    'Fecha en que el artista se presenta en el local (para rentabilidad por artista)';

